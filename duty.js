  // Возвращает пошлину в копейках. price - рубли (может быть с копейками) в копейках: priceKop
  function byScale(priceKop, scale, cap) {
    if (!Number.isFinite(priceKop) || priceKop < 0) throw new Error("Цена иска должна быть числом не меньше нуля");
    if (priceKop > 1e17) throw new Error("Цена иска слишком велика для расчёта (не более 1 000 000 000 000 000 ₽)");
    const price = BigInt(Math.round(priceKop));
    for (const [hi, baseRub, pct, from] of scale) {
      if (hi === Infinity || price <= BigInt(hi) * 100n) {
        // база + процент от превышения порога; 1 тысячная процента = 1/100000
        const over = price > BigInt(from) * 100n ? price - BigInt(from) * 100n : 0n;
        const add = (over * BigInt(pct) + 50000n) / 100000n; // копейки, округление до копейки
        let v = BigInt(baseRub) * 100n + add;
        const capK = BigInt(cap) * 100n;
        if (v > capK) v = capK;
        return Number(v);
      }
    }
    throw new Error("Не удалось определить интервал цены иска");
  }

