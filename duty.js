  // in: {court:'sou'|'arb', kind, party:'f'|'o', priceRub: number}
  // out: {kop, ref, note}
  function compute(inp) {
    const court = inp.court === "arb" ? "arb" : "sou";
    const k = KINDS[court][inp.kind];
    if (!k) throw new Error("Неизвестный вид требования");
    const scale = court === "arb" ? SCALE_ARB : SCALE_SOU;
    const cap = court === "arb" ? CAP_ARB : CAP_SOU;
    if (k.needsPrice) {
      const pk = Math.round(Number(inp.priceRub) * 100);
      let v = byScale(pk, scale, cap);
      let note = "";
      if (inp.kind === "order") {
        v = Math.round(v / 2);
        if (court === "arb" && v < kop(8000)) { v = kop(8000); note = "По судебному приказу берётся 50 % от этой суммы, но не менее 8 000 ₽ (минимум)."; }
        else note = "По судебному приказу берётся 50 % от этой суммы.";
      }
      return { kop: v, ref: k.ref, note };
    }
    const party = inp.party === "o" ? "o" : "f";
    const v = k[party];
    if (v === null || v === undefined) throw new Error("Для этого вида требования пошлина для выбранного заявителя в статье не установлена");
    return { kop: kop(v), ref: k.ref, note: k.hint || "" };
  }

